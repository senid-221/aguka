/** Facts the generator may build a question from. Everything else is a documented gap. */
export function generatableFacts(): VerifiedFact[] {
  return VERIFIED_FACTS.filter((f) => f.generationAllowed && f.reviewStatus === 'VERIFIED');
}

export function factsForModule(moduleCode: string | null): VerifiedFact[] {
  const all = generatableFacts();
  return moduleCode ? all.filter((f) => f.moduleCode === moduleCode) : all;
}
