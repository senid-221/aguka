/**
 * The only ground truth the question generator may write from.
 *
 * Every statement below is a transcription of a rule that is already cited in the
 * curriculum pack, with the same instrument and article. Nothing here is model
 * output: a speed limit, fine, category threshold or sign meaning that is not in
 * this file cannot become a correct answer, because the verification gate compares
 * every generated number against it.
 *
 * Rules that were searched for and not found are kept with generationAllowed = false
 * so the gap itself is documented instead of quietly filled by a model.
 */

const S = PRIMARY_SOURCES;

/** Most rules have no number; the helper supplies the empty values the type requires. */
type FactInput = Omit<VerifiedFact, 'reviewStatus' | 'article' | 'value' | 'unit' | 'distractorValues'> &
  Partial<Pick<VerifiedFact, 'reviewStatus' | 'article' | 'value' | 'unit' | 'distractorValues'>>;

function fact(input: FactInput): VerifiedFact {
  return {
    article: null,
    value: null,
    unit: null,
    distractorValues: [],
    ...input,
    reviewStatus: input.reviewStatus ?? 'VERIFIED',
  };
}

